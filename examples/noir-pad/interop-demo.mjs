/**
 * NoirPad live interop demo — proves the agent <-> app data loop:
 *   phone writes a note (app-data API)  ->  agent reads it (read_file /
 *   search_files / list_files)  ->  agent writes a reply note  ->  phone sees it.
 *
 * Usage:
 *   node examples/noir-pad/interop-demo.mjs [projectDir] [serverBase]
 * (projectDir defaults to cwd; serverBase defaults to http://127.0.0.1:5178)
 */
import { ToolRegistry, registerBuiltinTools } from "../../dist/core/tools/index.js";
import { loadConfig } from "../../dist/core/config.js";
import { MemoryStore } from "../../dist/core/memory/store.js";
import { Session } from "../../dist/core/session.js";
import { SkillManager } from "../../dist/core/skills/manager.js";
import { McpManager } from "../../dist/core/mcp/manager.js";
import { EventBus } from "../../dist/core/events.js";
import { createLogger } from "../../dist/core/logger.js";
import { resolve } from "node:path";

const projectDir = resolve(process.argv[2] ?? process.cwd());
const serverBase = process.argv[3] ?? "http://127.0.0.1:5178";
const { config } = loadConfig(projectDir);
const logger = createLogger("silent");
const events = new EventBus();
const memory = new MemoryStore(projectDir);
const skills = new SkillManager(projectDir, logger);
skills.load();
const registry = new ToolRegistry();
registerBuiltinTools(registry);
const session = new Session(projectDir, { title: "interop proof" });

const makeCtx = (s) => ({
  cwd: projectDir, config, logger, events, memory, session: s, skills,
  mcp: new McpManager(config, logger, events),
  subagents: null, swarm: null,
  taskBoard: { list: () => [], add: () => ({}), update: () => null, clear: () => {} },
});

const ctx = makeCtx(session);

console.log("== 1. agent reads a phone-created note (read_file) ==");
const r1 = await registry.execute("read_file", { path: ".noir/webapps/noirpad/data/notes/project-kick-off-abc1.md" }, ctx);
if (r1.isError) throw new Error(r1.content);
console.log(r1.content.split("\n").slice(0, 8).join("\n"));

console.log("\n== 2. agent greps all notes for 'noir' (search_files) ==");
const r2 = await registry.execute("search_files", { pattern: "noir", caseSensitive: false, include: "**/*.md" }, ctx);
console.log(r2.content.trim());

console.log("\n== 3. agent lists the webapp files (list_files) ==");
const r3 = await registry.execute("list_files", { pattern: ".noir/webapps/**" }, ctx);
console.log(r3.content.trim().split("\n").slice(0, 8).join("\n"));

console.log("\n== 4. agent writes a reply note the phone will see (write_file) ==");
const stamp = new Date().toISOString();
const reply = `---\ntitle: Agent summary\ntags: noir, auto\nupdated: ${stamp}\n---\n\nSummary generated by the NOIR agent: kick-off is scheduled, demo on Friday.\n`;
const r4 = await registry.execute("write_file", { path: ".noir/webapps/noirpad/data/notes/agent-summary-live.md", content: reply }, ctx);
console.log(r4.content.trim());

console.log("\n== 5. the phone fetches it back through the app API ==");
const res = await fetch(`${serverBase}/api/app-data/noirpad?file=notes/agent-summary-live.md`);
if (!res.ok) throw new Error(`app API returned ${res.status}`);
const body = await res.json();
console.log(`HTTP ${res.status}: ${body.content.split("\n").slice(-2).join(" ").trim()}`);

console.log("\nLIVE AGENT <-> NOIRPAD INTEROP: PASS");
process.exit(0);
